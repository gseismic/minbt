"""策略交易契约与默认 Exchange 实际使用的回放方法。"""

from typing import Dict, Mapping, Optional, Protocol, runtime_checkable

from .data import TimeBatch
from .result import OrderProtocol


BROKER_PROTOCOL_METHODS = (
    "submit_market_order", "submit_limit_order", "cancel_order",
    "get_position_size", "get_position_sizes", "get_total_equity",
    "get_equity", "get_cash", "get_positions", "order_target_size",
    "order_target_value", "order_target_percent", "close_position",
    "close_portfolio", "set_exit", "clear_exit", "get_exit", "add_exit",
    "get_active_order",
)


@runtime_checkable
class BrokerProtocol(Protocol):
    """保留已有策略方法，不要求继承内置 Broker 或增加通用命令层。"""

    def submit_market_order(self, symbol: str, qty: float, price: Optional[float] = None, **kwargs) -> OrderProtocol: ...
    def submit_limit_order(self, symbol: str, qty: float, limit_price: float, **kwargs) -> OrderProtocol: ...
    def cancel_order(self, order_id: str) -> OrderProtocol: ...
    def get_position_size(self, symbol: str, portfolio: Optional[str] = None) -> float: ...
    def get_position_sizes(self, portfolio: Optional[str] = None) -> Dict[str, float]: ...
    def get_total_equity(self) -> float: ...
    def get_equity(self, portfolio: Optional[str] = None) -> float: ...
    def get_cash(self, portfolio: Optional[str] = None, include_locked: bool = False) -> float: ...
    def get_positions(self, portfolio: Optional[str] = None): ...
    def order_target_size(self, symbol: str, target_size: float, price: Optional[float] = None, **kwargs) -> OrderProtocol: ...
    def order_target_value(self, symbol: str, target_value: float, price: Optional[float] = None, **kwargs) -> OrderProtocol: ...
    def order_target_percent(self, symbol: str, target_percent: float, price: Optional[float] = None, **kwargs) -> OrderProtocol: ...
    def close_position(self, symbol: str, price: Optional[float] = None, **kwargs) -> OrderProtocol: ...
    def close_portfolio(self, portfolio: str): ...
    def set_exit(self, order_id: str, **kwargs): ...
    def clear_exit(self, order_id: str, **kwargs): ...
    def get_exit(self, order_id: str): ...
    def add_exit(self, order_id: str, *, name: Optional[str] = None, condition, state=None): ...
    def get_active_order(self, symbol: str, *, portfolio: Optional[str] = None) -> Optional[OrderProtocol]: ...


@runtime_checkable
class ReplayBrokerProtocol(BrokerProtocol, Protocol):
    """补齐默认回放已有的推进方法，不增加公开生命周期框架。"""

    def process_market_batch(self, batch: TimeBatch) -> Mapping[str, float]: ...


__all__ = ["BrokerProtocol", "ReplayBrokerProtocol", "BROKER_PROTOCOL_METHODS"]
